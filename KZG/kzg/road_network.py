from __future__ import annotations

import csv
from pathlib import Path

from kzg.models import Edge


def _csv_data_rows(path: str | Path, field_names: tuple[str, ...]) -> list[list[str]]:
    rows = []
    with Path(path).open("r", encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        if reader.fieldnames is None:
            raise ValueError(f"{path}: CSV file is missing a header")
        reader.fieldnames = [name.strip() for name in reader.fieldnames]
        missing_fields = set(field_names).difference(reader.fieldnames)
        if missing_fields:
            names = ", ".join(sorted(missing_fields))
            raise ValueError(f"{path}: CSV file is missing required columns: {names}")
        for line_number, row in enumerate(reader, start=2):
            values = [row.get(name) for name in field_names]
            if all(value is None or not str(value).strip() for value in values):
                continue
            if any(value is None or not str(value).strip() for value in values):
                raise ValueError(f"{path}: CSV line {line_number} contains an empty required field")
            rows.append([str(value).strip() for value in values])
    return rows


def _text_data_rows(path: str | Path, field_count: int) -> list[list[str]]:
    lines = []
    for raw_line in Path(path).read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if line:
            lines.append(line)
    expected_count = None
    if lines and len(lines[0].split()) == 1:
        expected_count = int(lines.pop(0))
    rows = []
    for line in lines:
        fields = line.split()
        if len(fields) != field_count:
            raise ValueError(f"{path}: expected {field_count} fields, got {line!r}")
        rows.append(fields)
    if expected_count is not None and expected_count != len(rows):
        raise ValueError(f"{path}: header says {expected_count} rows, found {len(rows)}")
    return rows


def _data_rows(path: str | Path, field_names: tuple[str, ...]) -> list[list[str]]:
    if Path(path).suffix.lower() == ".csv":
        return _csv_data_rows(path, field_names)
    return _text_data_rows(path, len(field_names))


def _undirected_key(start_node: int, end_node: int) -> tuple[int, int]:
    start_node = int(start_node)
    end_node = int(end_node)
    return min(start_node, end_node), max(start_node, end_node)


def load_nodes(path: str | Path) -> dict[int, tuple[float, float]]:
    nodes: dict[int, tuple[float, float]] = {}
    for fields in _data_rows(path, ("node_id", "lon", "lat")):
        node_id = int(fields[0])
        lon = float(fields[1])
        lat = float(fields[2])
        if node_id in nodes:
            raise ValueError(f"duplicate node id: {node_id}")
        nodes[node_id] = (lon, lat)
    return nodes


def load_edges(path: str | Path) -> dict[int, Edge]:
    """Load every split edge exactly as generated by the Geohash preprocessor.

    Unlike the legacy STRtree project, parallel undirected edges are not
    collapsed: the processed trajectory references the exact new edge_id.
    """
    edges: dict[int, Edge] = {}
    for fields in _data_rows(path, ("edge_id", "start_node_id", "end_node_id")):
        edge_id = int(fields[0])
        start_node = int(fields[1])
        end_node = int(fields[2])
        if edge_id in edges:
            raise ValueError(f"duplicate edge id: {edge_id}")
        # Preserve the preprocessor's exact edge-id space, including rare
        # zero-topology/self-loop split records.  KZG authenticates the edge
        # identifier and time records; spatial membership is authenticated by
        # the cell payload, so dropping such IDs would break trajectory/cell
        # consistency.
        edges[edge_id] = Edge(edge_id, start_node, end_node)
    return edges


class RoadNetwork:
    """Road topology only.

    Spatial lookup is intentionally absent.  The legacy Shapely STRtree has
    been replaced by the directly-addressable Geohash cell index.
    """

    def __init__(self, nodes: dict[int, tuple[float, float]], edges: dict[int, Edge]):
        self.nodes = dict(nodes)
        self.edges = dict(edges)
        self.pair_to_edge_ids: dict[tuple[int, int], list[int]] = {}
        for edge_id in sorted(self.edges):
            edge = self.edges[edge_id]
            if edge.start_node not in self.nodes:
                raise ValueError(f"edge {edge_id} references missing start node {edge.start_node}")
            if edge.end_node not in self.nodes:
                raise ValueError(f"edge {edge_id} references missing end node {edge.end_node}")
            key = _undirected_key(edge.start_node, edge.end_node)
            self.pair_to_edge_ids.setdefault(key, []).append(edge_id)

    @classmethod
    def from_files(cls, node_path: str | Path, edge_path: str | Path) -> "RoadNetwork":
        return cls(load_nodes(node_path), load_edges(edge_path))

    def edge_ids_between(self, start_node: int, end_node: int) -> tuple[int, ...]:
        key = _undirected_key(start_node, end_node)
        return tuple(self.pair_to_edge_ids.get(key, []))

    def resolve_edge(self, start_node: int, end_node: int, parallel_policy: str = "error") -> int:
        if parallel_policy not in {"error", "min"}:
            raise ValueError(f"unsupported parallel policy: {parallel_policy!r}")
        edge_ids = self.edge_ids_between(start_node, end_node)
        if not edge_ids:
            raise KeyError(f"no edge between node {start_node} and node {end_node}")
        if len(edge_ids) > 1 and parallel_policy == "error":
            raise ValueError(f"multiple edges between node {start_node} and node {end_node}: {edge_ids}")
        return min(edge_ids)
